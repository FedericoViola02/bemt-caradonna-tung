def cn_integrato(xu, mcpu, xl, mcpl):
    """Normal-force coefficient from tabulated -Cp on the two surfaces (see module docstring)."""
    for xs, vs in ((xu, mcpu), (xl, mcpl)):
        assert len(xs) == len(vs), "x/c and Cp lists of different length (transcription error)"
        assert np.all(np.diff(xs) > 0), "x/c not increasing (transcription error)"
    x = np.linspace(0.0, 1.0, 4001)
    u = np.interp(x, list(xu) + [1.0], list(mcpu) + [0.0])
    l = np.interp(x, list(xl) + [1.0], list(mcpl) + [0.0])
    return np.trapezoid(u - l, x)


